// Bakes the plant models edited by hand (art/models/edited/<key>.glb, saved from Blender, keyed as
// dev/export-models.mjs named them) into src/three/plants/editedModels.js, from which src/three/plants/edited.js
// builds them in the game in the generators' place.
// Usage: node dev/edited-models.mjs
// In Blender's glTF export, keep Include › Data › Custom Properties on (the material names, shadow flags and height
// ride on them) and tick Data › Mesh › Attributes for a rock (its moss is the `_MOSS` attribute).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readGlb, meshesOf } from './glb.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const IN = path.join(HERE, '../art/models/edited');
const OUT = path.join(HERE, '../src/three/plants/editedModels.js');

/** A colour channel, linear 0–1, as 8-bit sRGB (the generators' colours are linear, as three keeps them). */
const srgb = (v) => {
  const c = Math.min(Math.max(v, 0), 1);
  return Math.round((c <= 0.0031308 ? c * 12.92 : 1.055 * c ** (1 / 2.4) - 0.055) * 255);
};
/** `array` as rounded integers at `scale` (and no -0). */
const ints = (array, scale) => Array.from(array, (v) => Math.round(v * scale) || 0);

/**
 * The model in a .glb as editedModels.js holds it: the height it was edited at (from its extras, else `height`) and
 * its parts, each with its material's name, shadow flags, p = corners in mm, n = normals ×1000, c = colours as 8-bit
 * sRGB (cs channels each: 4 where there is alpha, kept as it is), m = moss ×1000 and i = corner indices, where it
 * has them.
 */
export function bake(buffer, height) {
  const { meshes, extras } = meshesOf(readGlb(buffer));
  const parts = meshes.map((m) => {
    if (!m.material) throw new Error(`${m.name || 'a mesh'} has no material`);
    const part = { name: m.name, material: m.material, cast: Boolean(m.extras.castShadow ?? true), receive: Boolean(m.extras.receiveShadow ?? true), p: ints(m.position, 1000) };
    if (m.normal) part.n = ints(m.normal, 1000);
    if (m.color) {
      part.cs = m.colorSize;
      part.c = Array.from(m.color, (v, k) => (m.colorSize === 4 && k % 4 === 3 ? Math.round(Math.min(Math.max(v, 0), 1) * 255) : srgb(v)));
    }
    if (m.moss) part.m = ints(m.moss, 1000);
    if (m.index) part.i = Array.from(m.index);
    return part;
  });
  return { height: extras.height ?? height, parts };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { placedModels } = await import('../src/three/plants/valley.js');
  const { MODELS } = await import('../src/three/plants/woods.js');
  const heights = new Map(placedModels().map(({ key, height }) => [key, height]));
  for (const [kind, { seeds, height }] of Object.entries(MODELS)) for (let k = 1; k <= seeds; k++) heights.set(`woods-${kind}-${k}`, height);
  const files = fs.existsSync(IN) ? fs.readdirSync(IN).filter((f) => f.endsWith('.glb')).sort() : [];
  const lines = [];
  for (const file of files) {
    const key = path.basename(file, '.glb');
    if (!heights.has(key)) {
      console.warn(`${file}: no placed model is called ${key} (see dev/export-models.mjs); left out`);
      continue;
    }
    const { height, parts } = bake(fs.readFileSync(path.join(IN, file)), heights.get(key));
    for (const part of parts) {
      if (part.material.startsWith('stone') && !part.m) console.warn(`${file}: ${part.name} has no _MOSS attribute (tick Data › Mesh › Attributes in Blender's export); it will show no moss`);
    }
    const triangles = parts.reduce((n, p) => n + (p.i ? p.i.length : p.p.length / 3) / 3, 0);
    console.log(`${key}: ${parts.length} parts, ${triangles} triangles, at height ${height}`);
    const list = (name, a) => (a ? `, ${name}: [${a.join(',')}]` : '');
    lines.push(`  '${key}': { height: ${height}, parts: [\n${parts.map((p) => `    { name: ${JSON.stringify(p.name)}, material: ${JSON.stringify(p.material)}, cast: ${p.cast}, receive: ${p.receive}${p.cs ? `, cs: ${p.cs}` : ''}, p: [${p.p.join(',')}]${list('n', p.n)}${list('c', p.c)}${list('m', p.m)}${list('i', p.i)} },`).join('\n')}\n  ] },`);
  }
  fs.writeFileSync(OUT, `// Generated by dev/edited-models.mjs from art/models/edited/*.glb; do not edit by hand.
// Per model (by the key dev/export-models.mjs gave it): the height it was edited at and its parts, each with its
// material's name, shadow flags, p = corners in mm, n = normals ×1000, c = colours as 8-bit sRGB (cs channels each),
// m = moss ×1000 and i = corner indices, where it has them.
export const EDITED_MODELS = {${lines.map((l) => `\n${l}`).join('')}
};
`);
  console.log(`Wrote ${path.relative(process.cwd(), OUT)} (${lines.length} models, ${(fs.statSync(OUT).size / 1024).toFixed(1)} KB)`);
}
