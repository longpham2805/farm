// Turns tree models from Broken Vector's Low Poly Tree Pack (Collada .dae files, coloured from a 16 × 16 colour
// sheet of 4 × 4 solid blocks) into src/three/treeModels.js, which the game builds its trees from.
// Usage: node dev/tree-models.cjs <folder with the .dae files> [all]
// Converts the models in MODELS below; "all" converts every model in the folder, to compare them in dev/trees.html.
const fs = require('node:fs');
const path = require('node:path');

const MODELS = [
  // Pines and firs
  'Type1 03', 'Type1 04', 'Type2 02', 'Type2 03',
  // Leafy trees
  'Type0 05', 'Type3 01', 'Type3 02', 'Type4 03',
  // The round tree by the plots, also under the fruit
  'Type0 06',
  // Coconut palms
  'Type7 02', 'Type7 03',
];

const OUT = path.join(__dirname, '../src/three/treeModels.js');

const numbers = (text) => text.trim().split(/\s+/).map(Number);

/** The polygons of the file's one mesh: lists of corners, each { VERTEX: [x, y, z], TEXCOORD: [u, v] }. */
function parseDae(xml) {
  const sources = new Map();
  for (const [, id, body] of xml.matchAll(/<source id="([^"]+)">([\s\S]*?)<\/source>/g)) {
    const values = numbers(body.match(/<float_array[^>]*>([^<]*)<\/float_array>/)[1]);
    const stride = Number(body.match(/stride="(\d+)"/)[1]);
    sources.set(id, Array.from({ length: values.length / stride }, (_, k) => values.slice(k * stride, k * stride + stride)));
  }
  const [, verticesId, positionsId] = xml.match(/<vertices id="([^"]+)">\s*<input semantic="POSITION" source="#([^"]+)"\/>/);
  const lists = [...xml.matchAll(/<polylist[^>]*>([\s\S]*?)<\/polylist>/g)];
  if (lists.length !== 1) throw new Error(`expected one polylist, found ${lists.length}`);
  const list = lists[0][1];
  const inputs = [...list.matchAll(/<input semantic="(\w+)" source="#([^"]+)" offset="(\d+)"/g)].map(([, semantic, source, offset]) => ({
    semantic,
    data: sources.get(source === verticesId ? positionsId : source),
    offset: Number(offset),
  }));
  const stride = Math.max(...inputs.map((i) => i.offset)) + 1;
  const vcount = numbers(list.match(/<vcount>([^<]*)<\/vcount>/)[1]);
  const p = numbers(list.match(/<p>([^<]*)<\/p>/)[1]);
  const polys = [];
  let k = 0;
  for (const n of vcount) {
    const poly = [];
    for (let c = 0; c < n; c++, k += stride) {
      const corner = {};
      for (const { semantic, data, offset } of inputs) corner[semantic] = data[p[k + offset]];
      poly.push(corner);
    }
    polys.push(poly);
  }
  return polys;
}

/** Which of the sheet's 4 × 4 colour blocks a polygon is painted with, counted from the top left. */
function block(poly) {
  const u = poly.reduce((s, c) => s + c.TEXCOORD[0], 0) / poly.length;
  const v = poly.reduce((s, c) => s + c.TEXCOORD[1], 0) / poly.length;
  const col = Math.min(3, Math.floor((u - Math.floor(u)) * 4));
  const row = Math.min(3, Math.floor((1 - (v - Math.floor(v))) * 4));
  return row * 4 + col;
}

/**
 * One model: v = corner positions in mm (y up), t = triangles as corner indices,
 * c = [block, triangle count] runs, as the triangles are sorted by colour block.
 */
function convert(file) {
  const polys = parseDae(fs.readFileSync(file, 'utf8'));
  const corners = new Map();
  const v = [];
  const corner = ([x, y, z]) => {
    const mm = [x, y, z].map((n) => Math.round(n * 1000) || 0);
    const key = mm.join(',');
    if (!corners.has(key)) {
      corners.set(key, v.length / 3);
      v.push(...mm);
    }
    return corners.get(key);
  };
  const tris = [];
  for (const poly of polys) {
    const b = block(poly);
    const ids = poly.map((c) => corner(c.VERTEX));
    // Polygons are convex, so a fan splits them into triangles.
    for (let i = 1; i < ids.length - 1; i++) {
      const tri = [ids[0], ids[i], ids[i + 1]];
      if (new Set(tri).size === 3) tris.push({ b, tri });
    }
  }
  tris.sort((a, b) => a.b - b.b);
  const c = [];
  for (const { b } of tris) {
    if (c.length && c[c.length - 2] === b) c[c.length - 1]++;
    else c.push(b, 1);
  }
  return { v, t: tris.flatMap((t) => t.tri), c };
}

const [dir, which] = process.argv.slice(2);
if (!dir) {
  console.error('Usage: node dev/tree-models.cjs <folder with the .dae files> [all]');
  process.exit(1);
}
const names = which === 'all'
  ? fs.readdirSync(dir).filter((f) => f.endsWith('.dae')).map((f) => f.replace(/^Tree /, '').replace(/\.dae$/, '')).sort()
  : MODELS;
const lines = names.map((name) => {
  const { v, t, c } = convert(path.join(dir, `Tree ${name}.dae`));
  console.log(`${name}: ${t.length / 3} triangles, ${v.length / 3} corners`);
  return `  '${name}': {\n    v: [${v.join(',')}],\n    t: [${t.join(',')}],\n    c: [${c.join(',')}],\n  },`;
});
fs.writeFileSync(OUT, `// Generated by dev/tree-models.cjs from Broken Vector's Low Poly Tree Pack; do not edit by hand.
// Per model: v = corner positions in mm (y up), t = triangles as corner indices, and
// c = [colour-sheet block, triangle count] runs over the triangles in order (blocks 0-15 from the sheet's top left).
export const TREE_MODELS = {
${lines.join('\n')}
};
`);
console.log(`Wrote ${path.relative(process.cwd(), OUT)} (${(fs.statSync(OUT).size / 1024).toFixed(1)} KB)`);
